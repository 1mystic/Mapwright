"""Export the map as plain files: MAP.md (renders on GitHub and in most Markdown viewers), one
.mmd file per diagram, and the steps and verification as JSON."""

from __future__ import annotations

import json
import time
from pathlib import Path

from . import brief, render
from .server import Daemon, file_rows


def export(p, out: str) -> str:
    dest = Path(out)
    (dest / "diagrams").mkdir(parents=True, exist_ok=True)
    p.ensure()
    v = p.verify()
    steps = p.steps()
    md = [f"# {p.name}: project map", "",
          f"Generated by Mapwright on {time.strftime('%Y-%m-%d %H:%M')} from {len(p.cache)} files and {len(steps)} steps. "
          "Built by static analysis; nothing was executed.", "", "## Summary", "", "```text", brief.project_brief(p, 6000), "```", ""]
    for kind, title in render.KINDS.items():
        d = Daemon.diagram(None, p, kind, {"step": "live"})  # type: ignore[arg-type]
        (dest / "diagrams" / f"{kind}.mmd").write_text(d["mermaid"] + "\n")
        md += [f"## {title}", ""] + ([f"_{d['note']}_", ""] if d.get("note") else []) + ["```mermaid", d["mermaid"], "```", ""]
    md += ["## Steps", "", "| # | When | Title | Source | Files | + / − | Check |", "|---|---|---|---|---|---|---|"]
    for s in steps:
        sm = s["summary"]
        md.append(f"| {s['n']} | {time.strftime('%m-%d %H:%M', time.localtime(s['ts']))} | {render.label(s['title'], 80)} | {s['source']} | "
                  f"{sm['files']} | +{sm['added']} −{sm['removed']} | {render.label(s.get('title_check', 'ok'), 60)} |")
    md += ["", "## Todos", ""] + [f"- [{'x' if t['status'] == 'done' else ' '}] **{t['id']}** {t['text']}"
                                   + (f" — {'verified' if t.get('verified') else 'unverified'}: {t.get('reason')}" if t["status"] == "done" else "")
                                   for t in v["todos"]] + ["", "## Verification", ""]
    md += [f"- ⚠ {x['text']}" for x in v["problems"]] or ["Every claim, note, link and finished todo checks out against the code."]
    (dest / "MAP.md").write_text("\n".join(md) + "\n")
    (dest / "steps.json").write_text(json.dumps(steps, indent=1))
    (dest / "verification.json").write_text(json.dumps({k: v[k] for k in ("todos", "claims", "notes", "links", "problems")}, indent=1, default=str))
    return str(dest / "MAP.md")


__all__ = ["export", "file_rows"]
